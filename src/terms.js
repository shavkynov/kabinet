const cleanMode = (m) => (MODES.includes(m) ? m : 'novel');

/** Строка в словах нужного режима (для романа возвращается как есть). */
function termize(ru, mode) {
  return cleanMode(mode) === 'stories' && STORY[ru] !== undefined ? STORY[ru] : ru;
}

/** Авторский лист: 40 000 знаков с пробелами. */
const AUTHOR_SHEET = 40000;
const authorSheets = (chars) => Math.round((Math.max(0, chars) / AUTHOR_SHEET) * 100) / 100;

module.exports = { MODES, STORY, cleanMode, termize, authorSheets, AUTHOR_SHEET };
