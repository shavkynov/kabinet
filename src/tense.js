const INDEX = new Set(); // формы прошедшего времени (norm)

for (const line of VERBS) {
  const f = line.split('|');
  let stem = f[0].replace(/́/g, '');
  const refl = stem.startsWith('~');
  if (refl) stem = stem.slice(1);
  const masc = f[1] || `${stem}л`;
  const sfx = refl ? 'сь' : '';
  INDEX.add(norm(refl ? `${masc}ся` : masc));
  for (const e of ['ла', 'ло', 'ли']) INDEX.add(norm(`${stem}${e}${sfx}`));
}

// ---------- формы прошедшего времени ----------

const NOUN_STOP = new Set(`вокзал журнал сигнал финал идеал портал капитал материал персонал оригинал футбол ствол предел пепел
игла метла зола пила стрела скала могила сила мыла кукла`.split(/\s+/));

const PAST_FEM = /[аеиыуяюобвгджзкмнпрстфхцчшщ]л(?:а|о|и)(?:сь)?$/; // «взяла», «пришла», «смолкло»
const PAST_MASC = /(?:ал|ял|ил|ел|ул|ыл)(?:ся)?$/;

/** Форма прошедшего времени глагола (по нормализованному слову) или null. */
function pastInfo(raw, pos) {
  const w = norm(raw);
  if (INDEX.has(w)) return { dict: true };
  if (pos !== 'verb' || NOUN_STOP.has(w) || w.length < 4) return null;
  if (PAST_FEM.test(w)) {
    if (/(?:[аеиоуыэюя]тели|[аеиоуыэюя]нели)$/.test(w)) return null; // «родители»
    return { guess: w };
  }
  if (PAST_MASC.test(w) && w.length >= 6) return { guess: w };
  return null;
}

const PRESENT = /(?:[еёиуюая]т|[еи]шь)(?:ся)?$/;

// Формы будущего совершенного вида выглядят как настоящее («придёт», «скажет», «сделает»): настоящим временем они не являются.
// Видовой пары без словаря не узнать, поэтому здесь самые частые образцы: приставка + «-йд-», «-каж-», «-ним-», «-йм-», «-ложит»,
// «возьмёт», «станет» и приставка + простой несовершенный глагол («сделает», «прочитает», «напишет», «посмотрит»).
const PERF_PREFIX = '(?:при|у|вы|во|за|про|до|пере|по|подо|обо|ото|разо|на|с|со|об|от|раз|воз|вз|из|ис|над|под|пред|пре|рас)';
const PERS = '(?:ет|ешь|ем|ете|ут|ют|ит|ишь|им|ите|ат|ят)(?:ся)?';
const FUTURE_PERFECTIVE = new RegExp([
  `^(?:при|у|вы|во|за|про|до|пере|по|подо|обо|ото|разо|на|с|со|об|от|раз)йд${PERS}$`, // придёт, уйдёт, найдёт, выйдет
  `^${PERF_PREFIX}с?каж${PERS}$`, // скажет, покажет, расскажет
  '^при(?:дет|дешь|дем|дете|дут)$', // придёт (после «при» «й» выпадает)
  `^${PERF_PREFIX}ним${PERS}$`, // поднимет, снимет, обнимет
  `^${PERF_PREFIX}йм${PERS}$`, // поймёт, займёт
  `^${PERF_PREFIX}лож${PERS}$`, // положит, предложит, сложат
  '^возьм' + PERS + '$', '^стан' + PERS + '$',
  `^${PERF_PREFIX}(?:дела|чита|пиш|смотр|вид|слыш|дума|звон|стро|вар|рису|готов|плат|бер|ждет|зов|бьет|льет|шьет|пьет|еcт)${PERS}$`.replace('еcт', 'ест'),
].join('|'));
const isFuturePerfective = (w) => FUTURE_PERFECTIVE.test(w);

function isPresentVerb(raw, pos) {
  const w = norm(raw);
  if (pos !== 'verb' || w.length < 4) return false;
  if (isFuturePerfective(w)) return false;
  if (/(?:ть|ти|чь)(?:ся)?$/.test(w)) return false; // инфинитив
  return PRESENT.test(w) && !/(?:ал|ял|ил|ел|ул|ыл)(?:ся)?$/.test(w);
}

// ---------- воспоминания (прямая речь: speech.js) ----------

const MEMORY = /(?:^|[^а-я])(?:вспом|помн[ия]|тогда|раньше|ранее|когда-то|некогда|однажды|накануне|вчера|позавчера|прежде|давно|уже|только что|бывало|назад|в детстве|в юности|в молодости|в прошлом|в то время|до этого|в тот (?:день|вечер|раз|год)|тем (?:вечером|утром))/;

// ---------- придаточные предложения ----------
// Глаголы придаточных не считаются при определении основного времени и не помечаются: в тексте о прошлом
// «Он знал, что она любит его» нормально. Придаточное начинается с подчинительного слова после запятой
// и идёт до конца предложения или до запятой с союзом «и, а, но…» (дальше новая самостоятельная часть).
// Предложение, которое начинается с подчинительного слова («Когда он вошёл, она встала»), придаточное до первой запятой.
const SUB_MID = new Set(`что чтобы чтоб как когда пока если будто словно потому поскольку едва хотя где куда откуда почему зачем
  который которая которое которые которого которому которым которой которую которых которыми чей чья чьё чьи`.split(/\s+/));
const SUB_INITIAL = new Set('когда если пока едва хотя поскольку чтобы чтоб после прежде как'.split(' '));
const COORD = new Set('и а но да зато однако или'.split(' '));
const PERSONAL = new Set('он она они я мы ты вы'.split(' '));

// Слова автора при мысли или речи без кавычек: «Вода кипит при ста градусах, подумал он.»
const ATTRIB = /^(?:сказал|подумал|спросил|ответил|крикнул|прошептал|пробормотал|добавил|решил|понял|заметил|вспомнил|произнес|воскликнул|проговорил|продолжил|заявил|объявил|возразил|предположил|буркнул|пробурчал|шепнул|заключил|догадался|согласился)(?:а|и|ась|ись)?$/;

/**
 * Один абзац. words: [{ start, end, text, pos }], sents: [{ start, end }] (как в morph.js).
 * Возвращает { past, present, items: [{ start, end, wi, kind, conf, why }] }, kind: 'past' | 'present'.
 * Счётчики и находки только по главным предложениям повествования (без прямой речи, мыслей, воспоминаний и придаточных).
 * conf: 'high' (глагол другого времени рядом с глаголом основного или при герое) | 'low' (похоже на описание или общую истину:
 * возможный художественный приём). why: 'mixed' | 'actor' | 'description'.
 */
function analyzeTenseBlock(text, words, sents) {
  const ranges = speechRanges(text);
  const inSpeech = (pos) => ranges.some(([a, b]) => pos >= a && pos < b);
  const res = { past: 0, present: 0, items: [] };
  let scope = false; // идёт воспоминание
  for (const s of sents) {
    const sw = [];
    words.forEach((w, wi) => { if (w.start >= s.start && w.end <= s.end && !inSpeech(w.start)) sw.push(wi); });
    if (!sw.length) continue;
    const mem = MEMORY.test(norm(text.slice(s.start, s.end)));
    const present = sw.some((wi) => isPresentVerb(words[wi].text, words[wi].pos));
    const inMem = mem || (scope && !present);
    scope = inMem;

    // мысль или речь без кавычек: «…, подумал он» и «Он подумал: …»
    const thought = new Set();
    const sentText = text.slice(s.start, s.end);
    let sep = -1;
    for (const m of sentText.matchAll(/[,—–]/g)) sep = m.index;
    if (sep >= 0) {
      const tail = sw.filter((wi) => words[wi].start - s.start > sep);
      const head = sw.filter((wi) => words[wi].start - s.start < sep);
      if (tail.length > 0 && tail.length <= 5 && tail.some((wi) => ATTRIB.test(norm(words[wi].text)))
        && head.length >= 2 && !head.some((wi) => pastInfo(words[wi].text, words[wi].pos))) {
        head.forEach((wi) => thought.add(wi));
      }
    }
    const colon = sentText.indexOf(':');
    if (colon >= 0) {
      const before = sw.filter((wi) => words[wi].start - s.start < colon).slice(-3);
      if (before.some((wi) => ATTRIB.test(norm(words[wi].text)))) {
        sw.filter((wi) => words[wi].start - s.start > colon).forEach((wi) => thought.add(wi));
      }
    }

    // придаточные
    let sub = false;
    let leading = false; // придаточное в начале предложения: кончается на первой запятой
    let prev = null;
    let prevConjAfterComma = false;
    const first = words[sw[0]];
    if (SUB_INITIAL.has(norm(first.text)) && sentText.slice(first.end - s.start).includes(',')) { sub = true; leading = true; }
    const verbs = []; // главные глаголы предложения: { wi, kind }
    let actor = false;
    for (const wi of sw) {
      const w = words[wi];
      const low = norm(w.text);
      const comma = prev !== null && text.slice(words[prev].end, w.start).includes(',');
      if (comma) {
        if (sub && leading) { sub = false; leading = false; }
        else if (sub && COORD.has(low)) sub = false; // «…, и вышел»: новая самостоятельная часть
      }
      const afterConj = prev !== null && COORD.has(norm(words[prev].text)) && prevConjAfterComma;
      if (SUB_MID.has(low) && (comma || afterConj) && !(prev === null)) { sub = true; leading = false; }
      prevConjAfterComma = comma && COORD.has(low);
      prev = wi;
      if (sub || thought.has(wi) || inMem) continue;
      if (PERSONAL.has(low)) actor = true;
      let kind = null;
      if (isPresentVerb(w.text, w.pos)) kind = 'present';
      else if (pastInfo(w.text, w.pos)) kind = 'past';
      if (!kind) continue;
      verbs.push({ wi, kind });
    }
    for (const v of verbs) {
      if (v.kind === 'present') res.present += 1; else res.past += 1;
      const w = words[v.wi];
      const mixed = verbs.some((o) => o.kind !== v.kind);
      const why = mixed ? 'mixed' : actor ? 'actor' : 'description';
      res.items.push({ start: w.start, end: w.end, wi: v.wi, kind: v.kind, conf: why === 'description' ? 'low' : 'high', why });
    }
  }
  return res;
}

/** Основное время главы по числу глаголов: present | past | unknown. */
function detectBase(past, present) {
  if (past + present < 4 || past === present) return 'unknown';
  return present > past ? 'present' : 'past';
}

module.exports = { analyzeTenseBlock, detectBase, speechRanges, pastInfo, isPresentVerb, isFuturePerfective, ATTRIB };
