/** Часть речи одного слова: verb | noun | adj | adv | part (причастие и деепричастие) | pron | func (предлог, союз, частица) | num | other. */
// «Мимо» и «вокруг» бывают предлогом («мимо дома») и наречием («прошёл мимо.», «оглянулся вокруг.»): наречие, когда после них
// в предложении ничего нет (ctx.boundary). Если контекста нет (ctx.boundary не задан), остаётся как раньше.
const ADV_PREP = set('мимо вокруг');
// Начало неопределённого слова с «-то», «-нибудь», «-либо», «кое-»: «как-то» наречие, «что-то» местоимение.
const INDEFINITE_HEAD = { что: 'pron', как: 'adv', когда: 'adv', где: 'adv', куда: 'adv', откуда: 'adv', почему: 'adv', зачем: 'adv', отчего: 'adv' };

function classify(raw, ctx = {}) {
  const w = norm(raw);
  if (/^\d+(?:[.,:]\d+)*$/.test(w)) return 'num';
  if (!/[а-я]/.test(w)) return 'other';
  if (w.includes('-')) {
    const parts = w.split('-');
    if (/^(то|либо|нибудь|таки)$/.test(parts[parts.length - 1]) || parts[0] === 'кое') {
      const head = parts[0] === 'кое' ? parts[1] : parts[0];
      return INDEFINITE_HEAD[head] || classify(head, ctx);
    }
    if (parts[0] === 'по' && /(ому|ему|ски|и)$/.test(w)) return 'adv';
    return classify(parts[0], ctx);
  }
  if (w.length <= 1) return 'func';
  if (ADV_PREP.has(w) && ctx.boundary === true) return 'adv';
  // «у дома», «из дома»: после предлога это существительное, а не наречие «дома» (= «в доме»)
  if (w === 'дома' && ctx.prev && PREP.has(norm(ctx.prev))) return 'noun';
  if (PREP.has(w) || CONJ.has(w) || PARTICLE.has(w)) return 'func';
  if (PRON.has(w)) return 'pron';
  if (NUM.has(w)) return 'num';
  if (ADV.has(w)) return 'adv';
  if (w.length <= 2) return 'other';

  // причастия и деепричастия
  if (/(ущ|ющ|ащ|ящ|вш)(?:ий|ая|яя|ее|ие|его|ей|ему|им|ими|их|ую|юю|ой|ом|ых|ым|ые|ое|ый)(?:ся)?$/.test(w) && w.length > 6) return 'part';
  if (/(?:ем|им|ом)(?:ый|ая|ое|ые|ого|ой|ую|ому|ым|ых|ыми)$/.test(w) && w.length > 6 && !NOT_PART_RE.test(w)) return 'part';
  if (/(?:анн|янн|енн)(?:ый|ая|ое|ые|ого|ой|ую|ому|ым|ых|ыми)$/.test(w) && w.length > 7 && !NOT_PART_RE.test(w)) return 'part';
  if (/(?:ыт|ит|ут|от)(?:ый|ая|ое|ые|ого|ой|ую|ому|ым|ых|ыми)$/.test(w) && w.length > 6 && !NOT_PART_RE.test(w)) return 'part';
  if (/(?:вшись|вши|ясь|аясь)$/.test(w) && w.length > 5) return 'part';
  if (/(?:ав|яв|ув|ив|ев|ыв)(?:шись)?$/.test(w) && w.length >= 6) return 'part';
  if (GERUND.has(w)) return 'part';
  if (/(?:ывая|уя|юя|ося)$/.test(w) && w.length >= 6) return 'part'; // «рассказывая», «рискуя», «произнося»
  // краткие страдательные причастия: «написано», «открыто», «закрыта»
  if (/(?:[ая]н|ен)о$|(?:ыт|ит)[оа]$/.test(w) && w.length >= 6 && !NOUN_STOP.has(w)) return 'part';

  // прилагательные и наречия по основам частых слов, краткие формы, наречия после слов степени
  if (adjByStem(w)) return 'adj';
  if (shortAdj(w) && !NOUN_STOP.has(w)) return 'adj';
  if (adverbByStem(w) && !NOUN_STOP.has(w)) return 'adv';
  const prefixed = /^(?:без|бес|не)(.{4,})$/.exec(w); // «бесшумно», «нехорошо»
  if (prefixed && adverbByStem(prefixed[1]) && !NOUN_STOP.has(prefixed[1])) return 'adv';
  if (ctx.prev && DEGREE.has(norm(ctx.prev)) && /о$/.test(w) && w.length >= 4 && !NOUN_STOP.has(w)) return 'adv';

  // наречия по окончаниям
  if (/(?:нно|ельно|ивно|ично|чно|льно)$/.test(w) && w.length >= 6 && !NOUN_STOP.has(w)) return 'adv';
  // «дружески», «детски», «критически»; не «краски», «сосиски», «пляски», «записки» (перед «ск» стоит гласная, кроме «еск»)
  if (/(?:[бвгджзклмнпрстфхцчшщ]ск|еск)и$/.test(w) && w.length >= 6 && !NOUN_STOP.has(w)) return 'adv';
  if (/нно$/.test(w) && w.length >= 5 && !NOUN_STOP.has(w)) return 'adv'; // «сонно»
  if (/(?:[жш]н|ст[н])о$/.test(w) && w.length >= 6 && !NOUN_STOP.has(w)) return 'adv'; // «осторожно», «честно»: существительных на -жно, -шно, -стно нет
  if (/(?:лив|чив)о$/.test(w) && w.length >= 6 && !NOUN_STOP.has(w)) return 'adv'; // «торопливо», «задумчиво»

  if (NOUN_STOP.has(w)) return 'noun';
  const afterPrep = ctx.prev && PREP.has(norm(ctx.prev));

  // глаголы
  if (VERB_INF_EXTRA.has(w) || VERB_SHORT.has(w)) return 'verb';
  if (/(?:ться|тись|чься)$/.test(w)) return 'verb';
  if (/[аяеиуыо]ть$/.test(w) && w.length >= 4) return 'verb';
  if (/ти$/.test(w) && w.length >= 4 && !afterPrep) return 'verb';
  if (/(?:ешь|ишь|ется|ится|ются|ятся|утся|атся)$/.test(w) && w.length >= 5) return 'verb';
  if (/(?:ете|ите)$/.test(w) && w.length >= 5 && !afterPrep) return 'verb';
  if (/(?:ся|сь)$/.test(w) && w.length >= 5 && !/(?:ая|яя|ая)$/.test(w.slice(0, -2))) return 'verb';
  if (!afterPrep) {
    if (/(?:[аеиыуяюо]л)$/.test(w) && w.length >= 4) return 'verb';
    if (/(?:[аеиыуяю]л[аоие])$/.test(w) && w.length >= 4 && !/(?:лла|лло)$/.test(w)) return 'verb';
    if (/шл[аои]$/.test(w) && w.length >= 4) return 'verb'; // ушла, ушли
    if (/(?:[бвгджзкмнпрстфхцчшщ]л[аои])$/.test(w) && w.length >= 5 && !/л(?:ла|ло|ли)$/.test(w)) return 'verb'; // пришла, вышли, смолкло, погасла (не «Белла», «Нелли»)
    if (/(?:ет|ит|ут|ют|ат|ят)$/.test(w) && w.length >= 4) return 'verb';
  }

  // прилагательные
  if (/(?:ый|ий|ой)$/.test(w) && w.length >= 4 && (!/ой$/.test(w) || /[нвшкжчмлтдсхр]ой$/.test(w))) return 'adj';
  if (/[^аеиоуыэюя]ние$/.test(w)) return 'adj';
  if (/[кгхжшчщ]ие$/.test(w) && w.length >= 5) return 'adj';
  if (/(?:ые|ое|ее|ая|яя)$/.test(w) && w.length >= 5) return 'adj';
  if (/(?:ого|его|ому|ему|ую|юю|ых|ыми|ими|ым)$/.test(w) && w.length >= 6) return 'adj';
  if (/ым$/.test(w) && w.length >= 5) return 'adj'; // «белым», «ясным»
  if (/(?:[кгх]им|нним)$/.test(w) && w.length >= 6) return 'adj'; // «жарким», «последним»: ни существительных, ни глаголов на -ким, -гим, -хим, -нним нет

  return 'noun';
}

// Короткие страдательные причастия, которые отсекает порог длины: «был убит», «взята», «одеты».
const SHORT_PASSIVE_WORDS = set('одет одета одето одеты надет надета надето надеты убит убита убито убиты взят взята взято взяты сбит сбита сбито сбиты вымыт вымыта вымыто вымыты снят снята снято сняты обут обута обуто обуты сшит сшита сшито сшиты');

function isShortPassive(w) {
  if (SHORT_PASSIVE_WORDS.has(w)) return true;
  if (/^(?:за|от|вы|на|про|рас|ра|с)?(?:пер|тер)т[аоы]?$/.test(w)) return true; // «заперта», «стёрт», «отперто»
  if (w.length < 5) return false;
  if (SHORT_ADJ_STEMS.some((s) => w.startsWith(s)) || STATE_PART_STEMS.some((s) => w.startsWith(s)) || SHORT_ADJ_WORDS.has(w)) return false;
  return /(?:ен|ан|ян)(?:а|о|ы)?$/.test(w) || /(?:ыт|ит|ят|ут|ат)(?:а|о|ы)?$/.test(w) && w.length >= 6;
}

// Имя собственное: заглавная буква не в начале предложения и не после двоеточия, тире, кавычки («Павел», «Михаил» не глаголы).
function isMidCapital(text, index, word) {
  const ch = word[0];
  if (ch === ch.toLowerCase()) return false;
  const before = text.slice(Math.max(0, index - 40), index).trimEnd().slice(-1);
  return before !== '' && !/[.!?…:—–«„“"(]/.test(before);
}

/** Слова текста: { start, end, text, pos } */
function tokenize(text) {
  const out = [];
  let prev = '';
  const matches = [...text.matchAll(WORD_RE)];
  for (let i = 0; i < matches.length; i += 1) {
    const m = matches[i];
    const next = matches[i + 1];
    // после слова граница, если дальше слов нет или между словами знак препинания
    const boundary = !next || /[.,;:!?…—–()«»"“”]/.test(text.slice(m.index + m[0].length, next.index));
    let pos = classify(m[0], { prev, boundary });
    if ((pos === 'verb' || pos === 'adj' || pos === 'adv' || pos === 'part') && isMidCapital(text, m.index, m[0])) pos = 'noun';
    out.push({ start: m.index, end: m.index + m[0].length, text: m[0], pos });
    prev = m[0];
  }
  return out;
}

/** Страдательный залог: «был построен», «была освещена», «строился рабочими». Возвращает [{ start, end }]. */
function findPassive(words) {
  const spans = [];
  for (let i = 0; i < words.length; i += 1) {
    const w = words[i];
    const low = norm(w.text);
    // Определительные причастия («открытое окно», «забытый всеми») сюда не входят: это нормальная конструкция,
    // они остаются в категории «Причастия». Здесь только сказуемое: «был построен», «строился рабочими».
    // «был построен», «была написана», «будет сделано»
    if (BE.has(low)) {
      for (let j = i + 1; j <= i + 2 && j < words.length; j += 1) {
        const nx = norm(words[j].text);
        // «была большая комната»: между «была» и словом стоит прилагательное, значит это именная часть, не причастие.
        // Прилагательное по окончанию: «полностью», «сильно» (классификатор мог принять их за прилагательное) защитой не считаются
        if (j > i + 1 && words[j - 1].pos === 'adj' && /(?:ая|яя|ое|ее|ый|ий|ой|ые|ие|ую|юю|ого|его|ому|ему|ым|им|ом|ем)$/.test(norm(words[j - 1].text))) break;
        if (!BE_NOUN_STOP.has(nx) && isShortPassive(nx)) { spans.push({ start: w.start, end: words[j].end }); i = j; break; }
        if (words[j].pos === 'verb' || words[j].pos === 'noun' && j === i + 1 && !/^(?:уже|еще|давно|быстро)$/.test(nx)) break;
      }
      continue;
    }
    // «дом строился рабочими»: возвратный глагол и творительный падеж рядом
    if (w.pos === 'verb' && /(?:ся|сь)$/.test(low) && !REFLEXIVE_STEMS.some((s) => low.startsWith(s)) && !hasPronounSubject(words, i)) {
      for (let j = i + 1; j <= i + 3 && j < words.length; j += 1) {
        const nx = norm(words[j].text);
        const before = norm(words[j - 1].text);
        if (words[j].pos === 'verb') break;
        if (/(?:ом|ем|ой|ей|ами|ями|ыми|ими)$/.test(nx) && nx.length > 4 && ['noun', 'adj'].includes(words[j].pos) && !PREP.has(before) && !PRON.has(nx)) {
          if (NOT_AGENT_RE.test(norm(words[instrumentalHead(words, j)].text))) break; // время, образ действия, путь
          spans.push({ start: w.start, end: words[j].end });
          i = j;
          break;
        }
      }
    }
  }
  return spans;
}

// ---------- деление на предложения ----------
// Граница предложения: «.», «!», «?», «…» (с закрывающими кавычками и скобками), кроме случаев, когда знак не заканчивает предложение:
// сокращения («г.», «т. д.», «ул.»), инициалы («А. С. Пушкин»), числа («3.5»), номер в начале («1. Первое»),
// слова автора после реплики («Ты придёшь?» — спросила она), продолжение с маленькой буквы после «?», «!» и «…».

// После этих сокращений идёт название, имя или число, поэтому точка предложения не заканчивает.
const ABBR_INLINE = set(`ул им пр просп пер пл наб ш корп стр рис см табл гл ст акад проф доц ген полк лейт кап св тов напр англ нем фр лат греч
  т тт д п н к ч е с г-н г-жа`);
// Эти сокращения могут стоять в конце предложения: граница есть, если дальше с большой буквы («в 1999 г. Потом»).
const ABBR_END = set('гг руб коп тыс млн млрд экз мин сек');

const OPEN_QUOTES = /[«"„“(—–\s-]/;
const startsSentence = (rest) => {
  let i = 0;
  while (i < rest.length && OPEN_QUOTES.test(rest[i])) i += 1;
  return i >= rest.length || /[\p{Lu}\d]/u.test(rest[i]);
};

/** true, если знак препинания text[termStart..end) заканчивает предложение. segStart: начало текущего предложения. */
function isSentenceEnd(text, segStart, termStart, end) {
  const term = text.slice(termStart, end).replace(/["»”’)\]]+$/, '');
  const rest = text.slice(end);
  if (!rest.trim()) return true;
  if (!/^\s/.test(rest)) return false; // «3.5», «т.е.», «www.site.ru»: без пробела это не граница
  const next = rest.replace(/^\s+/, '');

  if (/[!?…]/.test(term)) {
    if (/^[—–]\s+\p{Ll}/u.test(next)) return false; // «Ты придёшь?» — спросила она.
    if (/^\p{Ll}/u.test(next)) return false; // «Он замолчал… и снова заговорил»
    return true;
  }

  // одиночная точка: смотрим на слово перед ней
  const before = text.slice(segStart, termStart);
  const tok = (/([\p{L}\p{N}-]+)$/u.exec(before) || [])[1] || '';
  const low = tok.toLowerCase();
  if (/^\d+$/.test(before.trim())) return false; // номер списка в начале: «1. Первое»
  if (/^\p{Lu}$/u.test(tok) && /(?:^|[\s«"„(—–-])$/.test(before.slice(0, before.length - tok.length))) return false; // инициал
  // «т. д.», «т. п.» могут заканчивать предложение, остальные «т. …» нет
  if ((low === 'д' || low === 'п') && /(?:^|[^\p{L}])т\.\s*$/iu.test(before.slice(0, before.length - tok.length))) return startsSentence(next);
  if ((low === 'г' || low === 'гг') && /\d\s*$/.test(before.slice(0, before.length - tok.length))) return startsSentence(next); // «в 1999 г.»
  if (low === 'г') return false; // «в г. Москве»: город, не год
  if (ABBR_END.has(low) && /\d\s*$/.test(before.slice(0, before.length - tok.length))) return startsSentence(next);
  if ((low === 'др' || low === 'пр') && /(?:^|[^\p{L}])и\s+$/iu.test(before.slice(0, before.length - tok.length))) return startsSentence(next); // «и др.», «и пр.»
  if (ABBR_INLINE.has(low)) return false;
  return true;
}

/** Предложения абзаца с числом слов: [{ start, end, words }] */
function sentences(text) {
  const out = [];
  const push = (from, to) => {
    const body = text.slice(from, to);
    const lead = body.length - body.trimStart().length;
    const trimmed = body.trim();
    if (!trimmed) return;
    const words = (trimmed.match(WORD_RE) || []).length;
    out.push({ start: from + lead, end: from + lead + trimmed.length, words });
  };
  let start = 0;
  const re = /[.!?…]+/g;
  let m;
  while ((m = re.exec(text)) !== null) {
    let end = m.index + m[0].length;
    while (end < text.length && /["»”’)\]]/.test(text[end])) end += 1;
    if (!isSentenceEnd(text, start, m.index, end)) continue;
    push(start, end);
    start = end;
  }
  push(start, text.length);
  return out;
}

/** Всё сразу для одного абзаца. */
function analyzeBlock(text) {
  const words = tokenize(text);
  return { words, passive: findPassive(words), sentences: sentences(text) };
}

// Начала предложений, с которых анафора («И… И… И…») бывает намеренным приёмом: для них в «Ритме» порог выше.
const ANAPHORA_STARTS = set('и а но');

module.exports = { classify, tokenize, findPassive, sentences, analyzeBlock, norm, ANAPHORA_STARTS };
