function adjByStem(w) {
  for (const n of [2, 3]) {
    if (w.length > n + 2 && ADJ_STEMS.has(w.slice(0, -n)) && ADJ_END.has(w.slice(-n))) return true;
  }
  return false;
}
function adverbByStem(w) {
  return w.length >= 4 && w.endsWith('о') && ADJ_STEMS.has(w.slice(0, -1));
}
function shortAdj(w) {
  if (SHORT_BARE.has(w)) return true;
  return w.length >= 4 && /[аыи]$/.test(w) && SHORT_STEMS.has(w.slice(0, -1));
}

