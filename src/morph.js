/** Личное местоимение-подлежащее в трёх словах перед глаголом (назад до другого глагола). */
function hasPronounSubject(words, i) {
  for (let k = i - 1; k >= 0 && k >= i - 3; k -= 1) {
    if (PERSONAL.has(norm(words[k].text))) return true;
    if (words[k].pos === 'verb') return false;
  }
  return false;
}

/** Слово, называющее предмет в группе творительного падежа: для «широкой улыбкой» это «улыбкой». */
function instrumentalHead(words, j) {
  let h = j;
  while (h + 1 < words.length && h < j + 2 && ['adj', 'part'].includes(words[h].pos) && INSTRUMENTAL_RE.test(norm(words[h + 1].text))) h += 1;
  return h;
}

