const TAUT_WINDOW = 2; // пара: соседние слова или через одно («рассказал мне рассказ»); дальше это уже обычный повтор корня
const TAUT_MIN_ROOT = 5; // общее начало корня, букв
const TAUT_MIN_SHARE = 0.6; // и не меньше такой доли короткого корня («прин-» в «принцип» мало)
const isVerbal = (w) => w.pos === 'verb' || w.pos === 'part';
function tautRoots(w, pos) {
  const low = w.toLowerCase().replace(/ё/g, 'е');
  const out = [low];
  if (pos !== 'verb' && pos !== 'part') return out; // приставки снимаем только у глаголов: у существительных они чаще часть корня
  for (const p of TAUT_PREFIXES) if (low.startsWith(p) && low.length - p.length >= 4) { out.push(low.slice(p.length)); break; }
  return out;
}
function commonStart(a, b) {
  let i = 0;
  while (i < a.length && i < b.length && a[i] === b[i]) i += 1;
  return i;
}
function findTautology(text, words, speech) {
  const out = [];
  const list = words.filter((w) => TAUT_POS.has(w.pos) && w.text.length >= 5 && !speech.some(([a, b]) => w.start >= a && w.start < b));
  for (let i = 0; i < list.length; i += 1) {
    for (let j = i + 1; j < list.length && j - i <= TAUT_WINDOW; j += 1) {
      const a = list[i];
      const b = list[j];
      if (a.pos === b.pos) continue; // одна часть речи: это «Повторы слов»
      if (/[.!?…]/.test(text.slice(a.end, b.start))) continue; // разные предложения
      const rb = tautRoots(b.text, b.pos);
      // одно слово глагольной формы, другое именной: «рассказал — рассказ». Два глагола («зарекомендовать — зарекомендую») — это повтор слова
      if (isVerbal(a) === isVerbal(b)) continue;
      if (!tautRoots(a.text, a.pos).some((x) => rb.some((y) => { const c = commonStart(x, y); return c >= TAUT_MIN_ROOT && c >= TAUT_MIN_SHARE * Math.min(x.length, y.length); }))) continue;
      out.push({ start: a.start, end: b.end, tip: `тавтология: однокоренные «${a.text.toLowerCase()}» и «${b.text.toLowerCase()}» рядом` });
      break;
    }
  }
  return out;
}

// ---------- лавина «который» и «что» ----------
const WHICH = new RegExp(`${L}(?:котор(?:ый|ая|ое|ые|ого|ой|ому|ым|ых|ыми|ую|ом))${E}|,\\s*что${E}`, 'giu');
const WHICH_MIN = 3;
function findWhichAvalanche(text, sentences, speech) {
  const out = [];
  const marks = [...text.matchAll(WHICH)].map((m) => m.index).filter((x) => !speech.some(([a, b]) => x >= a && x < b)); // слова героев не считаем
  if (marks.length < WHICH_MIN) return out;
  const sents = sentences && sentences.length ? sentences : [...text.matchAll(/[^.!?…]+[.!?…]*/g)].map((m) => ({ start: m.index, end: m.index + m[0].length }));
  for (const s of sents) {
    if (speech.some(([a, b]) => s.start >= a && s.start < b)) continue;
    const n = marks.filter((x) => x >= s.start && x < s.end).length;
    if (n >= WHICH_MIN) {
      let st = s.start;
      while (st < s.end && /\s/.test(text[st])) st += 1;
      out.push({ start: st, end: s.end, tip: `${n} придаточных на «который» и «что» в одном предложении: разбейте его или уберите лишние` });
    }
  }
  return out;
}

// ---------- лишнее «свой» и «его» ----------
const BODY = '(?:рук|ног|голов|глаз|лиц|плеч|спин|губ|палец|пальц|волос|шею|шее|груд|ладон|взгляд|сердц|уш[еи]|нос|рот|лоб|щ[её]к|колен|локт|кулак|шляп|шапк|пальто|куртк|плащ|сумк|очк|пиджак|платк|перчатк|ботинк|сапог|кепк|карман)\\p{L}*';
const OWN = [
  { re: new RegExp(`${L}(?:свой|своя|своё|свою|своей|своего|своему|своим|своими|свои|своих|своем)\\s+(?:\\p{L}+\\s+)?${BODY}${E}`, 'giu'), tip: '«свой» часто лишний: и так ясно, чья рука или шляпа («снял шляпу»)' },
];
// «Он поднял его руку»: притяжательное при подлежащем того же лица, если владелец не другой человек
const OWN_SUBJ = new RegExp(`${L}(?:он|она)\\s+(?:не\\s+)?\\p{L}+\\s+(?:(?:на|в|за|к|по)\\s+)?(?:его|её|ее)\\s+(?:\\p{L}+\\s+)?${BODY}${E}`, 'giu');
function findOwn(text, speech) {
  const out = scanTable(text, OWN, speech, 'own');
  for (const m of text.matchAll(OWN_SUBJ)) {
    const subj = m[0].slice(0, m[0].indexOf(' ')).toLowerCase();
    const poss = /(?:его)/i.test(m[0]) ? 'его' : 'её';
    if ((subj === 'он' && poss !== 'его') || (subj === 'она' && poss === 'его')) continue; // «он … её руку»: чужая
    if (speech.some(([a, b]) => m.index >= a && m.index < b)) continue;
    const i = m[0].search(/(?:его|её|ее)(?!\p{L})/iu);
    out.push({ start: m.index + i, end: m.index + m[0].length, tip: 'если рука или шляпа принадлежит самому герою, «его/её» лишнее; если чужая, оставьте' });
  }
  return out;
}

// ---------- ремарки при репликах ----------
// Ремарка — слова автора рядом с репликой, до 14 слов. Баллы за украшения; перегруз — два балла и больше.
const SAID_PLAIN = new RegExp(`${L}(?:сказал|сказала|сказали|спросил|спросила|спросили|ответил|ответила|ответили|произнёс|произнесла|произнес|крикнул|крикнула|закричал|закричала|добавил|добавила|продолжил|продолжила)${E}`, 'iu');
// Необычные глаголы вместо «сказал» и глаголы-«заменители» (улыбнулся: — …)
const SAID_FANCY = new RegExp(`${L}(?:воскликн|шепнул|прошепт|прошип|процед|изрёк|изрек|пробормот|рявкн|взревел|заявил|огрызн|отрезал|констатир|пророкот|выдохн|протянул|молвил|прорычал|пробасил|прогремел|завопил|хмыкнул|усмехнул|ухмыльнул|улыбнул|вздохнул|кивнул|нахмурил|рассмеял|засмеял|фыркнул|буркнул|взвизгнул|простонал|прохрипел|промурлыкал)\\p{L}*${E}`, 'iu');
const COMPARE = /(?<!\p{L})(?:словно|будто|как\s+(?:на|у|в|с|о|за|к|по|от))(?!\p{L})/iu; // «как бы» и «как раз» — не сравнение
const EMOTION_WITH = new RegExp(`${L}(?:с|со)\\s+(?:жаром|пылом|вызовом|насмешкой|издёвкой|издевкой|горечью|презрением|злостью|яростью|радостью|ужасом|болью|сарказмом|иронией|нежностью|вдохновением|\\p{L}*ством|\\p{L}*ием)${E}`, 'iu');
const GERUND = /(?:[аяуюеи]я|[жчшщ]а|ясь|ав|ив|ев|ув|ыв|вши|вшись)$/;
const NOT_GERUND = /(?:щая|щяя|вшая|нная|тая|ная|ая|яя|ое|ее|ие|ые)$/;
const REMARK_MAX_WORDS = 14;
const REMARK_OVERLOAD = 2;

/** Оценка одной ремарки: { score, why[] }. words — слова с частью речи в границах ремарки. */
function scoreRemark(text, words) {
  const why = [];
  let score = 0;
  const fancy = SAID_FANCY.exec(text);
  if (fancy) { score += 1; why.push(`необычный глагол «${fancy[0].toLowerCase()}»`); }
  const adv = words.find((w) => w.pos === 'adv' && w.text.length > 2 && !/^(?:потом|тогда|тут|там|здесь|снова|опять|еще|ещё|уже|так|затем|сейчас|вдруг|наконец|раз|навстречу|вперед|вперёд|назад|вверх|вниз|туда|сюда|прочь|домой|вместе|рядом|вокруг|мимо|сразу|тоже|также|потому|почти)$/i.test(w.text));
  if (adv) { score += 1; why.push(`наречие «${adv.text.toLowerCase()}»`); }
  const ger = words.find((w) => w.pos === 'part' && w.text.length >= 5 && GERUND.test(w.text.toLowerCase()) && !NOT_GERUND.test(w.text.toLowerCase()));
  if (ger) { score += 1; why.push(`деепричастие «${ger.text.toLowerCase()}»`); }
  const cmp = COMPARE.exec(text);
  if (cmp) { score += 1; why.push('сравнение'); }
  const em = EMOTION_WITH.exec(text);
  if (em) { score += 1; why.push(`«${em[0].toLowerCase()}»`); }
  return { score, why };
}

function findRemarks(text, words, speech) {
  const out = [];
  if (!speech.length) return out;
  const sorted = [...speech].sort((a, b) => a[0] - b[0]);
  const gaps = [];
  let at = 0;
  for (const [a, b] of sorted) { if (a > at) gaps.push([at, a]); at = Math.max(at, b); }
  if (at < text.length) gaps.push([at, text.length]);
  for (const [gs, ge] of gaps) {
    let s = gs;
    let e = ge;
    while (s < e && /[\s—–,.:;«»"„“”-]/.test(text[s])) s += 1;
    while (e > s && /[\s—–,.:;«»"„“”-]/.test(text[e - 1])) e -= 1;
    if (e - s < 4) continue;
    const seg = text.slice(s, e);
    const inSeg = words.filter((w) => w.start >= s && w.end <= e);
    if (inSeg.length > REMARK_MAX_WORDS) continue;
    // только настоящая ремарка: в ней есть глагол речи или «заменитель»
    if (!SAID_PLAIN.test(seg) && !SAID_FANCY.test(seg)) continue;
    const { score, why } = scoreRemark(seg, inSeg);
    if (score >= REMARK_OVERLOAD) out.push({ start: s, end: e, why });
  }
  return out;
}

// ---------- общий разбор абзаца ----------
const KINDS = ['chancery', 'weak', 'tell', 'chain', 'remark', 'redund', 'which', 'own'];

function scanTable(text, table, speech, kind) {
  const out = [];
  for (const { re, tip } of table) {
    re.lastIndex = 0;
    for (const m of text.matchAll(re)) {
      if (speech.some(([a, b]) => m.index >= a && m.index < b)) continue;
      out.push({ start: m.index, end: m.index + m[0].length, tip, kind });
    }
  }
  return out;
}

/** Убирает пересечения: при наложении остаётся более длинное место. */
function dedupe(list) {
  const sorted = [...list].sort((a, b) => a.start - b.start || (b.end - b.start) - (a.end - a.start));
  const out = [];
  for (const x of sorted) {
    const last = out[out.length - 1];
    if (last && x.start < last.end) continue;
    out.push(x);
  }
  return out;
}

/**
 * Разбор абзаца. words: слова из morph.analyzeBlock (нужны только для ремарок). kinds: какие виды искать.
 * Возвращает { chancery: [{ start, end, tip }], weak, tell, chain, remark } (позиции внутри text).
 */
function scanStyle(text, words, kinds, sentences) {
  const res = { chancery: [], weak: [], tell: [], chain: [], remark: [], redund: [], which: [], own: [] };
  const want = (k) => !kinds || kinds[k];
  if (!KINDS.some(want)) return res;
  const speech = speechRanges(text);
  if (want('chancery')) {
    // Штамп сам по себе — устоявшийся оборот, и он работает. Проблема, когда их несколько рядом: отмечаем, только если в абзаце их CLICHE_MIN и больше.
    let hits = dedupe(scanTable(text, CHANCERY, speech, 'chancery'));
    const cliches = hits.filter((h) => h.tip.startsWith('штамп'));
    if (cliches.length < CLICHE_MIN) hits = hits.filter((h) => !h.tip.startsWith('штамп'));
    else for (const h of cliches) h.tip = `штамп: в абзаце их ${cliches.length}, оставьте самый нужный`;
    res.chancery = hits;
  }
  if (want('weak')) res.weak = dedupe(scanTable(text, WEAK, speech, 'weak'));
  if (want('tell')) res.tell = dedupe(scanTable(text, TELL, speech, 'tell'));
  if (want('chain')) res.chain = findChains(text, speech).map((c) => ({ ...c, tip: 'цепочка отглагольных существительных: перестройте фразу глаголом' }));
  if (want('remark')) res.remark = findRemarks(text, words || [], speech).map((r) => ({ start: r.start, end: r.end, tip: `ремарка перегружена: ${r.why.join(', ')}` }));
  if (want('redund')) res.redund = dedupe([...scanTable(text, REDUND, speech, 'redund'), ...findTautology(text, words || [], speech)]);
  if (want('which')) res.which = findWhichAvalanche(text, sentences, speech);
  if (want('own')) res.own = dedupe(findOwn(text, speech));
  return res;
}

module.exports = { scanStyle, scoreRemark, findChains, KINDS, REMARK_OVERLOAD, REMARK_MAX_WORDS };
