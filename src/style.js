// ---------- цепочки отглагольных существительных ----------
// Отглагольное: «-ание/-ение/-тие/-вие» в любом падеже. Родительный (и похожие на него слова): -а -я -ы -и -ов -ев -ей -ий -ых -их...
const VN = /^\p{L}{2,}(?:ани|ени|ти|ви)(?:е|я|ю|ем|и|й|ям|ями|ях)$/u;
const GEN = /(?:а|я|ы|и|ов|ев|ей|ий|ых|их|ого|его|ой|ей)$/u;
const NOT_GEN = /(?:л|ла|ло|ли|ся|сь)$/u; // прошедшее время глаголов
const MIN_CHAIN = 3; // слов в цепочке
const MIN_VN = 2; // из них отглагольных

function findChains(text, speech) {
  const out = [];
  const tokens = [...text.matchAll(/\p{L}+(?:-\p{L}+)*/gu)].map((m) => ({ w: m[0].toLowerCase().replace(/ё/g, 'е'), s: m.index, e: m.index + m[0].length }));
  let run = [];
  const flush = () => {
    const vn = run.filter((t) => VN.test(t.w)).length;
    if (run.length >= MIN_CHAIN && vn >= MIN_VN) out.push({ start: run[0].s, end: run[run.length - 1].e });
    run = [];
  };
  for (let i = 0; i < tokens.length; i += 1) {
    const t = tokens[i];
    const joined = run.length && /^\s+$/.test(text.slice(run[run.length - 1].e, t.s)); // только пробелы: ни запятых, ни точек
    const inSpeech = speech.some(([a, b]) => t.s >= a && t.s < b);
    if (inSpeech) { flush(); continue; }
    if (VN.test(t.w) && !run.length) { run.push(t); continue; }
    if (run.length && joined && t.w.length >= 4 && GEN.test(t.w) && !NOT_GEN.test(t.w)) { run.push(t); continue; }
    flush();
    if (VN.test(t.w)) run.push(t);
  }
  flush();
  return out;
}

// ---------- ремарки при репликах ----------
// Ремарка — слова автора рядом с репликой, до 14 слов. Баллы за украшения; перегруз — два балла и больше.
const SAID_PLAIN = new RegExp(`${L}(?:сказал|сказала|сказали|спросил|спросила|спросили|ответил|ответила|ответили|произнёс|произнесла|произнес|крикнул|крикнула|закричал|закричала|добавил|добавила|продолжил|продолжила)${E}`, 'iu');
// Необычные глаголы вместо «сказал» и глаголы-«заменители» (улыбнулся: — …)
const SAID_FANCY = new RegExp(`${L}(?:воскликн|шепнул|прошепт|прошип|процед|изрёк|изрек|пробормот|рявкн|взревел|заявил|огрызн|отрезал|констатир|пророкот|выдохн|протянул|молвил|прорычал|пробасил|прогремел|завопил|хмыкнул|усмехнул|ухмыльнул|улыбнул|вздохнул|кивнул|нахмурил|рассмеял|засмеял|фыркнул|буркнул|взвизгнул|простонал|прохрипел|промурлыкал)\\p{L}*${E}`, 'iu');
const COMPARE = /(?<!\p{L})(?:как|словно|будто)(?!\p{L})/iu;
const EMOTION_WITH = new RegExp(`${L}(?:с|со)\\s+(?:жаром|пылом|вызовом|насмешкой|издёвкой|издевкой|горечью|презрением|злостью|яростью|радостью|ужасом|болью|сарказмом|иронией|нежностью|вдохновением|\\p{L}*ством|\\p{L}*ием)${E}`, 'iu');
const GERUND = /(?:[аяуюеи]я|[жчшщ]а|ясь|ав|ив|ев|ув|ыв|вши|вшись)$/;
const NOT_GERUND = /(?:щая|щяя|вшая|нная|тая|ная|ая|яя|ое|ее|ие|ые)$/;
const REMARK_MAX_WORDS = 14;
const REMARK_OVERLOAD = 2;

/** Оценка одной ремарки: { score, why[] }. words — слова с частью речи в границах ремарки. */
function scoreRemark(text, words) {
  const why = [];
  let score = 0;
  const fancy = SAID_FANCY.exec(text);
  if (fancy) { score += 1; why.push(`необычный глагол «${fancy[0].toLowerCase()}»`); }
  const adv = words.find((w) => w.pos === 'adv' && w.text.length > 2 && !/^(?:потом|тогда|тут|там|здесь|снова|опять|еще|ещё|уже|так|затем|сейчас|вдруг)$/i.test(w.text));
  if (adv) { score += 1; why.push(`наречие «${adv.text.toLowerCase()}»`); }
  const ger = words.find((w) => w.pos === 'part' && w.text.length >= 5 && GERUND.test(w.text.toLowerCase()) && !NOT_GERUND.test(w.text.toLowerCase()));
  if (ger) { score += 1; why.push(`деепричастие «${ger.text.toLowerCase()}»`); }
  const cmp = COMPARE.exec(text);
  if (cmp) { score += 1; why.push('сравнение'); }
  const em = EMOTION_WITH.exec(text);
  if (em) { score += 1; why.push(`«${em[0].toLowerCase()}»`); }
  return { score, why };
}

function findRemarks(text, words, speech) {
  const out = [];
  if (!speech.length) return out;
  const sorted = [...speech].sort((a, b) => a[0] - b[0]);
  const gaps = [];
  let at = 0;
  for (const [a, b] of sorted) { if (a > at) gaps.push([at, a]); at = Math.max(at, b); }
  if (at < text.length) gaps.push([at, text.length]);
  for (const [gs, ge] of gaps) {
    let s = gs;
    let e = ge;
    while (s < e && /[\s—–,.:;«»"„“”-]/.test(text[s])) s += 1;
    while (e > s && /[\s—–,.:;«»"„“”-]/.test(text[e - 1])) e -= 1;
    if (e - s < 4) continue;
    const seg = text.slice(s, e);
    const inSeg = words.filter((w) => w.start >= s && w.end <= e);
    if (inSeg.length > REMARK_MAX_WORDS) continue;
    // только настоящая ремарка: в ней есть глагол речи или «заменитель»
    if (!SAID_PLAIN.test(seg) && !SAID_FANCY.test(seg)) continue;
    const { score, why } = scoreRemark(seg, inSeg);
    if (score >= REMARK_OVERLOAD) out.push({ start: s, end: e, why });
  }
  return out;
}

// ---------- общий разбор абзаца ----------
const KINDS = ['chancery', 'weak', 'tell', 'chain', 'remark'];

function scanTable(text, table, speech, kind) {
  const out = [];
  for (const { re, tip } of table) {
    re.lastIndex = 0;
    for (const m of text.matchAll(re)) {
      if (speech.some(([a, b]) => m.index >= a && m.index < b)) continue;
      out.push({ start: m.index, end: m.index + m[0].length, tip, kind });
    }
  }
  return out;
}

/** Убирает пересечения: при наложении остаётся более длинное место. */
function dedupe(list) {
  const sorted = [...list].sort((a, b) => a.start - b.start || (b.end - b.start) - (a.end - a.start));
  const out = [];
  for (const x of sorted) {
    const last = out[out.length - 1];
    if (last && x.start < last.end) continue;
    out.push(x);
  }
  return out;
}

/**
 * Разбор абзаца. words: слова из morph.analyzeBlock (нужны только для ремарок). kinds: какие виды искать.
 * Возвращает { chancery: [{ start, end, tip }], weak, tell, chain, remark } (позиции внутри text).
 */
function scanStyle(text, words, kinds) {
  const res = { chancery: [], weak: [], tell: [], chain: [], remark: [] };
  const want = (k) => !kinds || kinds[k];
  if (!KINDS.some(want)) return res;
  const speech = speechRanges(text);
  if (want('chancery')) res.chancery = dedupe(scanTable(text, CHANCERY, speech, 'chancery'));
  if (want('weak')) res.weak = dedupe(scanTable(text, WEAK, speech, 'weak'));
  if (want('tell')) res.tell = dedupe(scanTable(text, TELL, speech, 'tell'));
  if (want('chain')) res.chain = findChains(text, speech).map((c) => ({ ...c, tip: 'цепочка отглагольных существительных: перестройте фразу глаголом' }));
  if (want('remark')) res.remark = findRemarks(text, words || [], speech).map((r) => ({ start: r.start, end: r.end, tip: `ремарка перегружена: ${r.why.join(', ')}` }));
  return res;
}

