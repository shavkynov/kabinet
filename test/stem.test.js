test('основы: формы одной лексемы объединяются (не менее 90 % групп)', () => {
  const bad = FORMS.filter((g) => new Set(g.map(key)).size !== 1).map((g) => g[0]);
  assert.ok(bad.length <= FORMS.length * 0.1, `не объединились: ${bad.join(', ')}`);
  assert.equal(key('смотрел'), key('смотрит'));
  assert.equal(key('улыбнулся'), key('улыбнулась'));
  assert.equal(key('вернулся'), key('вернулась'));
});

test('основы: слова с разными корнями различаются (не менее 90 % пар)', () => {
  const bad = UNRELATED.filter(([a, b]) => key(a) === key(b)).map(([a, b]) => `${a}—${b}`);
  assert.ok(bad.length <= UNRELATED.length * 0.1, `склеились: ${bad.join(', ')}`);
  for (const [a, b] of [['голос', 'голова'], ['порог', 'порода'], ['камень', 'камера'], ['берег', 'берёза']]) assert.notEqual(key(a), key(b));
});

test('основы: не русские и короткие слова возвращаются как есть', () => {
  assert.equal(stem('Doors'), 'doors');
  assert.equal(stem('дом'), 'дом');
  assert.equal(stem('ЁЖ'), 'еж');
});

// ---- повторы в тексте ----
function marked(paras, win = 25) {
  const seq = [];
  for (const p of paras) {
    const a = analyzeBlock(p);
    const proper = ed.properFlags(p, a.words, a.sentences);
    a.words.forEach((w, i) => seq.push({ text: w.text, pos: w.pos, proper: proper[i] }));
  }
  return [...ed.findRepeats(seq, win)].map((i) => seq[i].text.toLowerCase()).sort();
}

test('повторы: формы одного слова находятся', () => {
  assert.deepEqual(marked(['Дверь скрипнула. Он вошёл, закрыв за собой дверь, и прислонился к двери.']), ['двери', 'дверь', 'дверь']);
  assert.deepEqual(marked(['Он улыбнулся ей. Она тоже улыбнулась.']), ['улыбнулась', 'улыбнулся']);
  assert.deepEqual(marked(['Он вернулся домой поздно. Она вернулась утром.']), ['вернулась', 'вернулся']);
  assert.deepEqual(marked(['Она смотрела в окно. Он смотрит на неё.']), ['смотрела', 'смотрит']);
});

test('повторы: слова с разными корнями не считаются повтором', () => {
  assert.deepEqual(marked(['Он услышал голос. Потом повернул голову.']), []);
  assert.deepEqual(marked(['Он перешагнул порог дома. Эта порода собак редка.']), []);
  assert.deepEqual(marked(['Камень лежал на дороге. Фотограф навёл камеру.']), []);
  assert.deepEqual(marked(['Берег был пуст. Под берёзой стояла лавка.']), []);
});

test('повторы: окно поиска соблюдается', () => {
  const p = ['Дверь скрипнула. Он вошёл в комнату, где было тихо и пусто, и долго стоял у окна. Потом дверь закрылась.'];
  assert.deepEqual(marked(p, 30), ['дверь', 'дверь']);
  assert.deepEqual(marked(p, 5), []);
});

test('повторы: имена собственные не считаются, обычное слово после двоеточия считается', () => {
  assert.deepEqual(marked(['Анна пришла рано. Потом Анна ушла. Он видел Анну у реки.']), []);
  assert.deepEqual(marked(['Он сказал: Дождь идёт. Потом начался сильный дождь.']), ['дождь', 'дождь']);
  assert.deepEqual(marked(['Дверь скрипнула. Дверь закрылась.']), ['дверь', 'дверь']); // в начале предложения заглавная буква не признак имени
});

test('повторы: частые слова речи не считаются', () => {
  assert.deepEqual(marked(['Он сказал это. Она сказала то. Он снова сказал.']), []);
  assert.deepEqual(marked(['Он спросил её, и она ответила. Он спросил снова, и она ответила.']), []);
});

test('properFlags: заглавная не в начале предложения и не после тире, двоеточия, кавычки', () => {
  const t = 'Вчера Анна пришла. — Иван ушёл, — сказал он. Он сказал: Иди. «Стой» — крикнул Пётр.';
  const a = analyzeBlock(t);
  const flags = ed.properFlags(t, a.words, a.sentences);
  const names = a.words.filter((w, i) => flags[i]).map((w) => w.text);
  assert.deepEqual(names, ['Анна', 'Пётр']);
});
