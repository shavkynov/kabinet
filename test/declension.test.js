test('склонение: 70 имён и названий по пяти падежам, распознаётся не менее 95 % форм', () => {
  let total = 0;
  let found = 0;
  const missing = [];
  for (const [name, kind, ...expected] of TABLE) {
    const all = new Set([name, ...caseForms(name, { kind })].map((x) => x.toLowerCase()));
    for (const variants of expected) {
      total += 1;
      if (variants.split('/').some((v) => all.has(v.toLowerCase()))) found += 1;
      else missing.push(`${name}: ${variants}`);
    }
  }
  assert.ok(TABLE.length >= 60);
  assert.ok(found / total >= 0.95, `найдено ${found} из ${total}; нет: ${missing.join('; ')}`);
  assert.deepEqual(missing, [], 'сейчас ожидается полное совпадение; порог 95 % оставлен запасом на будущие дополнения таблицы');
});

test('склонение: однокоренные и похожие слова не подмешиваются', () => {
  const ivan = caseForms('Иван', { kind: 'character' });
  for (const w of ['Иванов', 'Иванова', 'Ивановым', 'Иваныч', 'Иванушка']) assert.ok(!ivan.has(w), `Иван не должен давать «${w}»`);
  const anna = caseForms('Анна', { kind: 'character' });
  for (const w of ['Анненский', 'Анненского', 'Аннушка', 'Аня']) assert.ok(!anna.has(w), `Анна не должна давать «${w}»`);
  assert.ok(!caseForms('Анна', { kind: 'character' }).has('Анна'), 'именительный падеж в формы не входит');
});

test('склонение: неизменяемые и неподходящие слова форм не получают', () => {
  for (const name of ['Ли', 'Мэри', 'Нелли', 'Гюго', 'Anna', 'NASA', 'Мими', '', '   ']) {
    assert.equal(caseForms(name, { kind: 'character' }).size, 0, `«${name}»`);
  }
  assert.equal(caseForms('Один Два Три Четыре Пять Шесть', { kind: 'place' }).size, 0, 'слишком длинное для названия');
  // слово в середине названия, которое не изменяется
  assert.ok(caseForms('Ростов на Дону', { kind: 'place' }).has('Ростовом на Дону'));
  assert.ok(caseForms('Ростов-на-Дону', { kind: 'place' }).has('Ростовом-на-Дону'));
});

test('склонение: обычные слова из «Имён в тексте» и вариант с «е» вместо «ё»', () => {
  const old = caseForms('старик', { kind: 'character' });
  assert.ok(old.has('старика') && old.has('старику') && old.has('стариком') && old.has('старике'));
  const semen = caseForms('Семён', { kind: 'character' });
  assert.ok(semen.has('Семена') && semen.has('Семёна') && semen.has('Семен'));
});

test('склонение: nameForms не склоняет заново уже готовые формы и не повторяет явные имена', () => {
  const forms = nameForms('Анна', ['Анны', 'Аня', 'Анне'], { kind: 'character' });
  assert.ok(forms.includes('Ане') && forms.includes('Аню'), 'формы псевдонима «Аня»');
  assert.ok(forms.includes('Анну') && forms.includes('Анной'));
  assert.ok(!forms.includes('Анны') && !forms.includes('Анне'), 'явные имена в результат не входят');
  assert.ok(!forms.some((f) => /^Анн[оы]го$|^Анн[оы]му$/.test(f)), 'форма «Анной» не склоняется как прилагательное');
  assert.equal(new Set(forms.map((f) => f.toLowerCase())).size, forms.length, 'без повторов');
});
