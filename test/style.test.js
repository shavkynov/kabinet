'use strict';
// Стиль текста (src/style.js): канцелярит и штампы, слабые глаголы, «назвал, а не показал», цепочки, ремарки.
const test = require('node:test');
const assert = require('node:assert');
const { scanStyle } = require('../src/style');
const { analyzeBlock } = require('../src/morph');

const ALL = { chancery: true, weak: true, tell: true, chain: true, remark: true };
const scan = (text, kinds = ALL) => scanStyle(text, analyzeBlock(text).words, kinds);
const found = (text, kind) => scan(text)[kind].map((h) => text.slice(h.start, h.end));

test('канцелярит: типичные обороты найдены, обычный текст нет', () => {
  const t = 'В целях проверки данный отряд осуществлял разведку. Капитан принял решение оказать помощь раненым.';
  assert.deepEqual(found(t, 'chancery'), ['В целях', 'данный', 'осуществлял', 'принял решение', 'оказать помощь']);
  assert.deepEqual(found('Он вышел из дома и пошёл к реке. Там было тихо.', 'chancery'), []);
});

test('штампы отмечаются только скоплением: один в абзаце — нормальный оборот', () => {
  assert.deepEqual(found('Сердце ёкнуло, а по спине пробежал холодок.', 'chancery'), ['Сердце ёкнуло', 'по спине пробежал холодок']);
  assert.deepEqual(found('Когда она шагнула в тень, сердце ёкнуло.', 'chancery'), []);
});

test('речь героев не проверяется (канцелярит, чувства, слабые глаголы)', () => {
  const t = '— Данный вопрос является важным, — сказал он. — Я начал бояться и был зол.';
  const r = scan(t);
  assert.deepEqual(r.chancery, []);
  assert.deepEqual(r.tell, []);
  assert.deepEqual(r.weak, []);
  const q = 'Он сказал: «Это является данностью». Но сам осуществлял контроль.';
  assert.deepEqual(found(q, 'chancery'), ['осуществлял']);
});

test('слабые глаголы: фазовые и «находился»; «пытался» не трогаем (попытка бывает сюжетом)', () => {
  const t = 'Он начал идти, потом стал думать и пытался открыть дверь. Склад находился на краю города.';
  assert.deepEqual(found(t, 'weak'), ['начал идти', 'стал думать', 'находился']);
  // «стал» с существительным или прилагательным не фазовый глагол
  assert.deepEqual(found('Он стал врачом, а она стала красивой. Начало работы назначили на утро.', 'weak'), []);
});

test('«назвал, а не показал»: чувства и посредники', () => {
  const t = 'Он был зол. Ей стало страшно. Она почувствовала острый страх. Он увидел, как дверь открылась.';
  assert.deepEqual(found(t, 'tell'), ['был зол', 'Ей стало страшно', 'почувствовала острый страх', 'увидел, как']);
  assert.deepEqual(found('Он сжал кулаки и отвернулся к окну.', 'tell'), []);
});

test('цепочки отглагольных существительных: от трёх слов и двух отглагольных', () => {
  assert.deepEqual(found('Осуществление проверки выполнения требований имело место вчера.', 'chain'), ['Осуществление проверки выполнения требований']);
  assert.deepEqual(found('Выяснение причины отсутствия желания затянулось.', 'chain'), ['Выяснение причины отсутствия желания']);
  // одно отглагольное слово, запятые и обычные существительные цепочкой не считаются
  assert.deepEqual(found('Ожидание затянулось. Он ждал прибытия, поезда, друзей. Дом отца брата.', 'chain'), []);
});

test('ремарка: перегруз — два балла и больше (необычный глагол, наречие, деепричастие, сравнение, «с жаром»)', () => {
  const heavy = scan('— Я не пойду, — прошипел он, скалясь.');
  assert.equal(heavy.remark.length, 1);
  assert.match(heavy.remark[0].tip, /прошипел/);
  assert.match(heavy.remark[0].tip, /скалясь/);
  assert.deepEqual(scan('— Я не пойду, — сказал он.').remark, []);
  assert.deepEqual(scan('— Я не пойду, — сказал он тихо.').remark, []); // один балл (наречие)
  assert.deepEqual(scan('— Привет, — улыбнулась она. — Как дела?').remark, []); // один балл (глагол-«заменитель»)
  assert.equal(scan('— Нет, — отрезал он с вызовом, словно ударил.').remark.length, 1);
});

test('ремарка: длинное повествование рядом с репликой ремаркой не считается', () => {
  const t = '— Идём, — сказал он. Потом он долго шёл по пыльной дороге, глядя на облака и вспоминая, как прошипел когда-то отец, скалясь.';
  assert.deepEqual(scan(t).remark, []);
});

test('только выбранные виды ищутся', () => {
  const t = 'Данный человек начал идти.';
  const r = scan(t, { weak: true });
  assert.equal(r.weak.length, 1);
  assert.deepEqual(r.chancery, []);
});

const scan2 = (text, kinds) => { const a = analyzeBlock(text); return scanStyle(text, a.words, kinds, a.sentences); };
const found2 = (text, kind) => scan2(text, { [kind]: true })[kind].map((h) => text.slice(h.start, h.end));

test('плеоназмы и лишние уточнения', () => {
  assert.deepEqual(found('В феврале месяце он вернулся обратно и кивнул головой. Она упала вниз.', 'redund'), ['В феврале месяце', 'вернулся обратно', 'кивнул головой', 'упала вниз']);
  assert.deepEqual(found('Он вернулся домой и поднял голову. Она упала на пол.', 'redund'), []);
});

test('тавтология: однокоренные разных частей речи рядом; далеко и в разных предложениях нет', () => {
  assert.deepEqual(found('Вспоминаю случай, случившийся со мной.', 'redund'), []); // корень из четырёх букв: сознательно не ловим, слишком много совпадений («принял — принцип»)
  assert.deepEqual(found('Он рассказал мне рассказ.', 'redund'), ['рассказал мне рассказ']);
  assert.deepEqual(found('Он рассказал много. Потом был рассказ.', 'redund'), []);
  assert.deepEqual(found('Он сказал слово и открыл словарь.', 'redund'), []);
});

test('лавина «который» и «что»: три и больше в одном предложении', () => {
  const heavy = 'Это человек, который знал, что дом, который стоит у реки, продаётся.';
  assert.equal(found(heavy, 'which').length, 1);
  assert.deepEqual(found('Это человек, который знал, что дом продаётся.', 'which'), []);
  assert.deepEqual(found('— Я знаю, что дом, который стоит у реки, что-то значит, — сказал он, что-то.', 'which'), []);
});

test('«свой» и «его»: лишнее притяжательное при частях тела и одежде', () => {
  assert.deepEqual(found('Он снял свою шляпу и вытер свой лоб.', 'own'), ['свою шляпу', 'свой лоб']);
  assert.deepEqual(found('Она поправила её волосы.', 'own'), ['её волосы']);
  assert.deepEqual(found('Он взял её руку и пошёл к своему дому.', 'own'), []); // чужая рука; дом не часть тела
  assert.deepEqual(found('— Я сниму свою шляпу, — сказал он.', 'own'), []); // реплика героя
});

test('калибровка по живой прозе: слова-омонимы не срабатывают', () => {
  assert.deepEqual(found('Давление возросло, судя по данным скафандра. Подвезли бочки с вином. Она смотрит с грустной улыбкой.', 'chancery'), []);
  assert.deepEqual(found('Подвезли бочки с вином. Она смотрит с грустной улыбкой.', 'tell'), []);
  assert.deepEqual(found('Выдохнул с облегчением, со страхом, от радости.', 'tell'), ['с облегчением', 'со страхом', 'от радости']);
  // однокоренные далеко друг от друга — обычный повтор корня, а не тавтология
  assert.deepEqual(found('Он увернулся от удара, заблокировал второй и ударил сам.', 'redund'), []);
  assert.deepEqual(found('Он слегка заметил, что ему сказали. Заметил, что видит.', 'tell'), []);
});

test('ремарка: «наконец», «навстречу», «как бы», «в который раз» не считаются украшениями', () => {
  assert.deepEqual(scan2('— Ладно. — Наконец, вздохнула она.', { remark: true }).remark, []);
  assert.deepEqual(scan2('— Напился? — Сказал ангел, шагая навстречу.', { remark: true }).remark, []);
  assert.deepEqual(scan2('— Ну и чего? — Спросил чиновник, думая, как бы наказать охрану.', { remark: true }).remark, []);
  assert.equal(scan2('— Ты сомневаешься? — Мягко спросил ангел, как на щенка.', { remark: true }).remark.length, 1);
});

test('расширенные конструкции: усилия, роль посредника и названные эмоции', () => {
  assert.deepEqual(found('Нарцисса прикладывает значительные усилия, чтобы доказать ценность семьи.', 'chancery'), ['прикладывает значительные усилия']);
  assert.deepEqual(found('Она выступает в роли посредника между сторонами.', 'chancery'), ['выступает в роли']);
  assert.deepEqual(found('Он смотрит на неё с настоящим удивлением.', 'tell'), ['с настоящим удивлением']);
  assert.deepEqual(found('Она ответила с искренней радостью и от глубокого разочарования замолчала.', 'tell'), ['с искренней радостью', 'от глубокого разочарования']);
});

test('расширенные конструкции не помечают нейтральные формулировки', () => {
  assert.deepEqual(found('Она приложила усилия к двери. Он выступил на сцене в роли Гамлета.', 'chancery'), []);
  assert.deepEqual(found('Он смотрел на неё с большим интересом к разговору.', 'tell'), []);
});

test('калибровка по классике (Чернышевский, Горький): омонимы и обычные определения', () => {
  assert.deepEqual(found('Он очнулся от вина. Было счастливое время.', 'tell'), []);
  assert.deepEqual(found('Он был рад, а она напугана.', 'tell'), ['был рад']);
  assert.deepEqual(found('Он спустился в подвал, в подвале было сыро. Он принял принцип.', 'redund'), []);
  assert.deepEqual(found('Он очень хотел познакомиться, и знакомство состоялось.', 'redund'), ['познакомиться, и знакомство']);
  assert.deepEqual(found('Аристократия среди демократии, партии и компании.', 'chain'), []);
  assert.deepEqual(found('Он начал повесть, но не закончил.', 'weak'), []);
});
