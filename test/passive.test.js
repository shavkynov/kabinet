'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const m = require('../src/morph');
const cases = require('./passive-cases');

const spans = (t) => m.findPassive(m.tokenize(t)).map((s) => t.slice(s.start, s.end));

test('страдательный залог: 21 размеченное предложение, ложных 0, пропусков не больше 2 (все спорные)', () => {
  const falsePositives = [];
  const misses = [];
  for (const c of cases) {
    const got = spans(c.t);
    for (const x of got) if (!c.expect.includes(x)) falsePositives.push(`${c.t} → ${x}`);
    for (const x of c.expect) if (!got.includes(x)) misses.push({ t: c.t, disputed: !!c.disputed });
  }
  assert.deepEqual(falsePositives, []);
  assert.ok(misses.length <= 2, `пропусков ${misses.length}: ${misses.map((x) => x.t).join('; ')}`);
  assert.deepEqual(misses.filter((x) => !x.disputed), [], 'пропущен неспорный случай');
});

test('страдательный залог: краткие прилагательные и состояния не отмечаются', () => {
  const not = [
    'Он был силён.', 'Она была влюблена.', 'Он был знаком с ней.', 'Он был занят работой.', 'Она была замужем и счастлива.',
    'Брат был нужен им.', 'Старик был голоден.', 'Он был удивлён.', 'Он был пьян.', 'Она была обязана ему всем.',
  ];
  assert.deepEqual(not.filter((t) => spans(t).length), []);
});

test('страдательный залог: возвратные глаголы с творительным без страдательного смысла не отмечаются', () => {
  const not = ['Он ударился головой.', 'Она хвасталась успехами.', 'Он рисковал жизнью.', 'Они поделились радостью.', 'Он пренебрегал советами.'];
  assert.deepEqual(not.filter((t) => spans(t).length), []);
  // настоящие страдательные конструкции находятся по-прежнему
  assert.deepEqual(spans('Крыша была покрыта снегом.'), ['была покрыта']);
  assert.deepEqual(spans('Улицы заливались дождём.'), ['заливались дождём']);
});

test('страдательный залог: краткие причастия на -рт и короткие формы', () => {
  assert.deepEqual(spans('Дверь была заперта.'), ['была заперта']);
  assert.deepEqual(spans('Он был убит в бою.'), ['был убит']);
  assert.deepEqual(spans('Деньги были взяты без спроса.'), ['были взяты']);
  assert.deepEqual(spans('Это была черта его характера.'), []); // «черта» существительное
  assert.deepEqual(spans('Она была мертва.'), []);
});


// ---------- аудит: возвратный глагол и творительный сами пассива не делают («Дом строился годами») ----------

test('пассив: творительный времени, образа действия и пути не деятель («Дом строился годами»)', () => {
  const not = [
    'Дом строился годами.', 'Город строился веками.', 'Работа тянулась неделями.', 'Они ссорились днями.',
    'Война продолжалась десятилетиями.', 'Дом строился долгими годами.', 'Ребёнок смеялся звонким смехом.',
    'Старик поклонился низким поклоном.', 'Дорога вилась лесом.', 'Вода разлилась рекой.', 'Огонь разгорелся ярким пламенем.',
  ];
  assert.deepEqual(not.filter((t) => spans(t).length), []);
  // деятель и средство остаются пассивом
  assert.deepEqual(spans('Дом строился рабочими.'), ['строился рабочими']);
  assert.deepEqual(spans('Дом строился опытными рабочими.'), ['строился опытными']);
  assert.deepEqual(spans('Мост строился инженерами.'), ['строился инженерами']);
  assert.deepEqual(spans('Зал освещался сотнями свечей.'), ['освещался сотнями']);
});

test('пассив: подлежащее-личное местоимение при возвратном глаголе пассивом не считается', () => {
  const not = ['Он улыбнулся широкой улыбкой.', 'Она умылась холодной водой.', 'Они расстались друзьями.', 'Он вернулся героем.',
    'Она каждое утро умывалась холодной водой.', 'Он считался лучшим учеником.', 'Мы поделились хлебом.'];
  assert.deepEqual(not.filter((t) => spans(t).length), []);
});

test('пассив: «была + существительное» не принимается за краткое причастие', () => {
  const not = ['Это была большая комната с низким потолком.', 'Там была стена.', 'Это была сцена.', 'В углу была узкая лестница.',
    'Это была красивая страна с древней историей.', 'Была цена и была дата.'];
  assert.deepEqual(not.filter((t) => spans(t).length), []);
  // настоящие краткие причастия по-прежнему находятся, в том числе через наречие
  assert.deepEqual(spans('Комната была освещена свечами.'), ['была освещена']);
  assert.deepEqual(spans('Дверь была полностью разрушена.'), ['была полностью разрушена']);
  assert.deepEqual(spans('Письмо было отправлено вчера.'), ['было отправлено']);
});
