//! Компактный дополнительный словарь современной бытовой/ИТ-лексики и литературных
//! форм, отсутствующих в классическом словаре Лебедева (ru_RU, BSD).

use std::collections::HashSet;
use std::sync::OnceLock;

static EXTRA_WORDS: OnceLock<HashSet<String>> = OnceLock::new();

fn add_masc_hard(s: &mut HashSet<String>, base: &str) {
    for suf in ["", "а", "у", "ом", "е", "ы", "ов", "ам", "ами", "ах"] {
        s.insert(format!("{}{}", base, suf));
    }
}

fn add_masc_velar(s: &mut HashSet<String>, base: &str) {
    for suf in ["", "а", "у", "ом", "е", "и", "ов", "ам", "ами", "ах"] {
        s.insert(format!("{}{}", base, suf));
    }
}

fn add_masc_sibilant(s: &mut HashSet<String>, base: &str) {
    for suf in ["", "а", "у", "ом", "ем", "е", "и", "ей", "ам", "ами", "ах"] {
        s.insert(format!("{}{}", base, suf));
    }
}

fn add_fem_a(s: &mut HashSet<String>, stem: &str) {
    for suf in ["а", "ы", "е", "у", "ой", "ою", "ам", "ами", "ах"] {
        s.insert(format!("{}{}", stem, suf));
    }
}

fn add_fem_ka(s: &mut HashSet<String>, stem: &str, gen_pl: &str) {
    for suf in ["ка", "ки", "ке", "ку", "кой", "кою", "кам", "ками", "ках"] {
        s.insert(format!("{}{}", stem, suf));
    }
    s.insert(format!("{}{}", stem, gen_pl));
}

fn add_fem_iya(s: &mut HashSet<String>, stem: &str) {
    for suf in ["ия", "ии", "ию", "ией", "иею", "ий", "иям", "иями", "иях"] {
        s.insert(format!("{}{}", stem, suf));
    }
}

fn add_neut_o(s: &mut HashSet<String>, stem: &str) {
    for suf in ["о", "а", "у", "ом", "е", "ам", "ами", "ах"] {
        s.insert(format!("{}{}", stem, suf));
    }
}

fn add_adj(s: &mut HashSet<String>, stem: &str, nom_m: &str) {
    s.insert(format!("{}{}", stem, nom_m));
    for suf in [
        "ая", "ое", "ые", "ие", "ого", "ой", "ому", "ым", "им", "ом", "ую", "ых", "их", "ыми", "ими", "ою",
    ] {
        s.insert(format!("{}{}", stem, suf));
    }
}

fn add_participle_nn(s: &mut HashSet<String>, stem: &str) {
    add_adj(s, &format!("{}н", stem), "ный");
    for suf in ["", "а", "о", "ы"] {
        s.insert(format!("{}{}", stem, suf));
    }
}

fn add_verb_past(s: &mut HashSet<String>, stem: &str, refl: bool) {
    let tail = if refl { "сь" } else { "" };
    if !refl {
        s.insert(stem.to_string());
    }
    for suf in ["л", "ла", "ло", "ли"] {
        if refl {
            let r = if suf == "л" { "ся" } else { tail };
            s.insert(format!("{}{}{}", stem, suf, r));
        } else {
            s.insert(format!("{}{}", stem, suf));
        }
    }
}

