/** Добавить карточку; повторное добавление с тем же видом и названием дополняет псевдонимы. */
function card(kind, title, aliases = []) {
  if (!KINDS.has(kind)) throw new Error(`неизвестный вид карточки: ${kind}`);
  if (typeof title !== 'string') throw new Error('название карточки должно быть строкой');
  const key = `${kind}\u0000${title}`;
  let c = byKey.get(key);
  if (!c) {
    c = { kind, title, aliases: new Set() };
    byKey.set(key, c);
    cases.push(c);
  }
  for (const a of aliases) {
    if (typeof a !== 'string') throw new Error('псевдоним должен быть строкой');
    c.aliases.add(a);
  }
}

