// ---------- сборка JSON ----------

const output = cases
  .map((c) => {
    const aliases = [...c.aliases].sort(cmp);
    // Предметы в project.js cardIndex склоняются как места — так же и в Rust-тесте.
    const declKind = c.kind === 'item' ? 'place' : c.kind;
    const forms = [...new Set(nameForms(c.title, aliases, { kind: declKind }))].sort(cmp);
    return { kind: c.kind, title: c.title, aliases, forms };
  })
  .sort((a, b) => cmp(a.kind, b.kind) || cmp(a.title, b.title));

const variants = output.reduce((sum, c) => sum + c.forms.length, 0);

// ---------- проверки корпуса ----------

if (output.length < 250 || output.length > 400) throw new Error(`ожидается около 300 карточек, а получилось ${output.length}`);
if (variants < 8000) throw new Error(`ожидается не менее 8000 вариантов, а получилось ${variants}`);
const keys = new Set();
for (const c of output) {
  const key = `${c.kind}\u0000${c.title}`;
  if (keys.has(key)) throw new Error(`повтор карточки: ${key}`);
  keys.add(key);
  for (let i = 1; i < c.aliases.length; i += 1) {
    if (cmp(c.aliases[i - 1], c.aliases[i]) >= 0) throw new Error(`псевдонимы не отсортированы: ${c.title}`);
  }
  for (let i = 1; i < c.forms.length; i += 1) {
    if (cmp(c.forms[i - 1], c.forms[i]) >= 0) throw new Error(`формы не отсортированы: ${c.title}`);
  }
}

const doc = { variants, cases: output };
