// Карточки-имена получают псевдонимы в духе «Имён в тексте»: имя с отчеством, полное имя,
// обратный порядок «фамилия + имя», инициал, уменьшительное. Это заодно проверяет ветки
// name_forms с явными именами и дедупликацией.
function addFirstNames(names, gender, offset) {
  const patr = gender === 'f' ? PATRONYMIC_F : PATRONYMIC_M;
  const sur = gender === 'f' ? SURNAME_F : SURNAME_M;
  names.forEach((title, i) => {
    const n = offset + i;
    const aliases = [
      `${title} ${patr[n % patr.length]}`,
      `${title} ${patr[(n + 3) % patr.length]} ${sur[n % sur.length]}`,
      `${title} ${patr[(n + 6) % patr.length]}`,
      `${sur[(n + 7) % sur.length]} ${title}`,
      `${title[0]}. ${sur[n % sur.length]}`,
      `${title} ${patr[(n + 5) % patr.length]} ${sur[(n + 3) % sur.length]}`,
      `${title} ${patr[(n + 8) % patr.length]} ${sur[(n + 6) % sur.length]}`,
    ];
    const dims = DIMINUTIVES[title];
    if (dims) aliases.push(...dims);
    card('character', title, aliases);
  });
}

/** Женская форма фамилии по мужской, если правило однозначное. */
function feminineSurname(s) {
  if (/(?:ий)$/i.test(s)) return `${s.slice(0, -2)}ая`;
  if (/(?:ой)$/i.test(s)) return `${s.slice(0, -2)}ая`;
  if (/(?:ый)$/i.test(s)) return `${s.slice(0, -2)}ая`;
  if (/(?:ов|ев|ёв|ин|ын)$/i.test(s)) return `${s}а`;
  return null;
}

/** Мужская форма фамилии по женской, если правило однозначное. */
function masculineSurname(s) {
  if (/(?:ая)$/i.test(s)) return `${s.slice(0, -2)}ий`;
  if (/(?:ов|ев|ёв|ин|ын)а$/i.test(s)) return s.slice(0, -1);
  return null;
}

function addSurnames(names, gender, offset) {
  const firsts = gender === 'f' ? FEMALE_FIRST_EXTRA : MALE_FIRST_EXTRA;
  names.forEach((title, i) => {
    const n = offset + i;
    const first = firsts[n % firsts.length];
    const first2 = firsts[(n + 4) % firsts.length];
    const partner = gender === 'f' ? masculineSurname(title) : feminineSurname(title);
    const first3 = firsts[(n + 2) % firsts.length];
    const aliases = [`${first} ${title}`, `${title} ${first2}`, `${title} ${first3}`, `${first[0]}. ${title}`];
    if (partner) aliases.push(partner);
    card('character', title, aliases);
  });
}

